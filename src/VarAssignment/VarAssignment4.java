package VarAssignment;

public class VarAssignment4 {
    public static void main(String[] args) {
        byte a = 10;
        short b = 200;
        // byte c = 150; -> byte 데이터 타입의 표현 범위는 -128부터 127까지
        int d = 300;
        // long e = 5000000000; -> 5000000000L로 표기
        // float f = 5.7; -> 5.7f로 표기
        double g = 5.7;
        boolean h = true;
        char i = 'A';
    }
}