package cooperation;

public class Bus {
    private int busNumber;  // 버스 번호
    private int passengerCount; // 승객 수
    private int money; // 버스 수입

    public Bus(int busNumber, int passengerCount, int money) {
        this.busNumber = busNumber;
        this.passengerCount = passengerCount;
        this.money = money;
    }
}
