package reference;

public class Subject {
    String subjectName;
    int scorePoint;

    public void setSubjectName(String sName) {
        subjectName = sName;
    }

    public void setScorePoint(int scorePoint) {
        this.scorePoint = scorePoint;
    }

    public String getSubjectName() {
        return subjectName;
    }

    public int getScorePoint() {
        return scorePoint;
    }
}
